// comparision operator

console.log( 2 == "2"); // it will print true because == operator only checks the value not the data type
console.log( 2 === "2"); // it will print false because === operator checks both value and data type
console.log( 2 != "2"); // it will print false because != operator only checks the value not the data type
console.log( 2 !== "2"); // it will print true because !== operator checks both value and data type

console.log( 1 > "2"); // it will print false because 1 is not greater than 2
console.log( 2 < "2");  // it will print false because 2 is not less than 2
console.log( 2 >= "2"); // it will print true because 2 is greater than or equal to 2
console.log( 2 <= "2"); // it will print true because 2 is less than or equal to 2


console.log(null > 0); // it will print false because null is not greater than 0
console.log(null == 0); // it will print false because null is not equal to 0
console.log(null >= 0); // it will print true because null is considered as 0 in this case


console.log(undefined > 0); // it will print false because undefined is not greater than 0
console.log(undefined == 0);    
// it will print false because undefined is not equal to 0
console.log(undefined >= 0); // it will print false because undefined is not greater than or equal to 0


console.log("five" > 3); // it will print false because "five" is not a number and cannot be compared to 3


